`timescale 1 ns / 1 ps

module myip_v1_0 #
(
    // BRAM interface parameters (user side)
    parameter integer BRAM_DWIDTH = 8,
    parameter integer BRAM_AWIDTH = 13,
    parameter integer BRAM_DEPTH  = 8192,

    // Parameters of Axi Slave Bus Interface S00_AXI
    parameter integer C_S00_AXI_DATA_WIDTH = 32,
    parameter integer C_S00_AXI_ADDR_WIDTH = 17
)
(
    // ==========================
    // User-side simple interface
    // ==========================
    output wire                       user_start,
    input  wire                       user_done,

    output wire [BRAM_AWIDTH-1:0]     user_bram_addr,
    output wire [BRAM_DWIDTH-1:0]     user_bram_wdata,
    output wire                       user_bram_we,
    input  wire [BRAM_DWIDTH-1:0]     user_bram_rdata,

    // ==========================
    // AXI4-Lite Slave Interface
    // ==========================
    input  wire                       s00_axi_aclk,
    input  wire                       s00_axi_aresetn,
    input  wire [C_S00_AXI_ADDR_WIDTH-1 : 0] s00_axi_awaddr,
    input  wire [2 : 0]               s00_axi_awprot,
    input  wire                       s00_axi_awvalid,
    output wire                       s00_axi_awready,
    input  wire [C_S00_AXI_DATA_WIDTH-1 : 0] s00_axi_wdata,
    input  wire [(C_S00_AXI_DATA_WIDTH/8)-1 : 0] s00_axi_wstrb,
    input  wire                       s00_axi_wvalid,
    output wire                       s00_axi_wready,
    output wire [1 : 0]               s00_axi_bresp,
    output wire                       s00_axi_bvalid,
    input  wire                       s00_axi_bready,
    input  wire [C_S00_AXI_ADDR_WIDTH-1 : 0] s00_axi_araddr,
    input  wire [2 : 0]               s00_axi_arprot,
    input  wire                       s00_axi_arvalid,
    output wire                       s00_axi_arready,
    output wire [C_S00_AXI_DATA_WIDTH-1 : 0] s00_axi_rdata,
    output wire [1 : 0]               s00_axi_rresp,
    output wire                       s00_axi_rvalid,
    input  wire                       s00_axi_rready
);

    // ------------------------------------------------------------------------
    // Internal wires between AXI register block (myip_v1_0_S00_AXI)
    // and the simple user/BRAM interface exposed to the top module
    // ------------------------------------------------------------------------

    // BRAM-style bus used inside the AXI wrapper
    wire [BRAM_AWIDTH-1:0] bram_addr;
    wire                   bram_ce;
    wire                   bram_we;
    wire [BRAM_DWIDTH-1:0] bram_q;
    wire [BRAM_DWIDTH-1:0] bram_d;

    // Control/status signals coming from the AXI register map
    wire start;
    wire weight_start;
    wire [3:0] odata_addr;
    wire w_c1_we, w_c2_we, w_fc_we, p_we, cnn_out_rd;
    wire w_c1_done_int, w_c2_done_int, w_fc_done_int, p_done_int;
    wire done;

    // Map BRAM bus to simple user BRAM port
    assign user_bram_addr  = bram_addr;
    assign user_bram_wdata = bram_d;
    assign user_bram_we    = bram_we;

    // BRAM read data returned from user logic into AXI wrapper
    assign bram_q = user_bram_rdata;

    // Map start/done handshake:
    //  - 'start' is generated by AXI side and goes out as user_start
    //  - 'done' is asserted by user logic and observed by AXI side
    assign user_start = start;
    assign done       = user_done;

    // We do not use the fine-grain done signals in this simplified design.
    // Tie them low so STATUS register logic in S00_AXI still synthesizes.
    assign w_c1_done_int = 1'b0;
    assign w_c2_done_int = 1'b0;
    assign w_fc_done_int = 1'b0;
    assign p_done_int    = 1'b0;

    // ------------------------------------------------------------------------
    // Instantiation of AXI4-Lite slave + register / BRAM controller
    // ------------------------------------------------------------------------
    myip_v1_0_S00_AXI #(
        .BRAM_DWIDTH       (BRAM_DWIDTH),
        .BRAM_AWIDTH       (BRAM_AWIDTH),
        .BRAM_DEPTH        (BRAM_DEPTH),

        .C_S_AXI_DATA_WIDTH(C_S00_AXI_DATA_WIDTH),
        .C_S_AXI_ADDR_WIDTH(C_S00_AXI_ADDR_WIDTH)
    ) myip_v1_0_S00_AXI_inst (
        // BRAM Interface (internal)
        .bram_addr (bram_addr),
        .bram_ce   (bram_ce),
        .bram_we   (bram_we),
        .bram_q    (bram_q),
        .bram_d    (bram_d),

        // Control/data ports
        .start         (start),
        .done          (done),
        .weight_start  (weight_start),
        //.idata_port  (),
        .odata_addr    (odata_addr),
        //.odata_port  (),

        .cnn_out_rd    (cnn_out_rd),
        .p_we          (p_we),
        .w_c1_we       (w_c1_we),
        .w_c2_we       (w_c2_we),
        .w_fc_we       (w_fc_we),

        .p_done        (p_done_int),
        .w_c1_done     (w_c1_done_int),
        .w_c2_done     (w_c2_done_int),
        .w_fc_done     (w_fc_done_int),

        //.idata_cnt   (),

        // AXI4-Lite Slave Interface
        .S_AXI_ACLK    (s00_axi_aclk),
        .S_AXI_ARESETN (s00_axi_aresetn),
        .S_AXI_AWADDR  (s00_axi_awaddr),
        .S_AXI_AWPROT  (s00_axi_awprot),
        .S_AXI_AWVALID (s00_axi_awvalid),
        .S_AXI_AWREADY (s00_axi_awready),
        .S_AXI_WDATA   (s00_axi_wdata),
        .S_AXI_WSTRB   (s00_axi_wstrb),
        .S_AXI_WVALID  (s00_axi_wvalid),
        .S_AXI_WREADY  (s00_axi_wready),
        .S_AXI_BRESP   (s00_axi_bresp),
        .S_AXI_BVALID  (s00_axi_bvalid),
        .S_AXI_BREADY  (s00_axi_bready),
        .S_AXI_ARADDR  (s00_axi_araddr),
        .S_AXI_ARPROT  (s00_axi_arprot),
        .S_AXI_ARVALID (s00_axi_arvalid),
        .S_AXI_ARREADY (s00_axi_arready),
        .S_AXI_RDATA   (s00_axi_rdata),
        .S_AXI_RRESP   (s00_axi_rresp),
        .S_AXI_RVALID  (s00_axi_rvalid),
        .S_AXI_RREADY  (s00_axi_rready)
    );

endmodule
